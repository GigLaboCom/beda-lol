def variants(w, k_max):
    out = {w: (0, '')}
    ops = []
    for i, c in enumerate(w):
        for t in BREAK.get(c, []): ops.append(('b', i, t))
        ops.append(('d', i, None))
    for k in range(1, k_max + 1):
        for combo in itertools.combinations(ops, k):
            if len({o[1] for o in combo}) < k: continue
            ch = list(w); d = []
            for kind, i, t in combo:
                if kind == 'b': ch[i] = t; d.append(f"{w[i].upper()}→{t.upper()}")
                else: ch[i] = ''; d.append(f"−{w[i].upper()}")
            r = ''.join(ch)
            if r and (r not in out or out[r][0] > k): out[r] = (k, ' '.join(d))
    return out
