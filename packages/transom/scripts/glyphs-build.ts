/**
 * Builds the glyph tables from the font (inputs: `glyphs.config.ts`). Used by
 * `gen-glyphs.ts`, which writes the files, and by the freshness test, which
 * compares them with a fresh run. Node only.
 */
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { type BreakKey, breaksFor } from '@beda/core';
import { create, type Font } from 'fontkitten';
import { GLYPHS_CONFIG, type GlyphsConfig } from '../glyphs.config';
import { dropFor, pieceDropFor, UNITS_PER_EM } from '../src/geometry';
import {
  type Box,
  type Command,
  centroid,
  hangAngle,
  inkBox,
  inkPoint,
  inkRegions,
  nailTargets,
  outlineCentroid,
  type Point,
  pathData,
  piecePolygon,
  rasterize,
  snapNails,
  splitInk,
} from '../src/glyph-analysis';
import type { Glyph, GlyphBreak } from '../src/glyphs';
import { PIECES } from '../src/pieces';

/** Measurements the tests check but the site doesn't need. */
export interface GlyphCheck {
  /** Distance between the exact outline centroid and the raster centroid, em. */
  centroidDelta?: number;
}
export interface BreakCheck {
  /** Ink pixels inside and outside the piece. */
  inside: number;
  outside: number;
  /** Connected ink regions left after the piece is gone. */
  regions: number;
}

export interface GlyphBuild {
  /** Every drawable character, in code point order. */
  charset: string[];
  falling: string[];
  glyphs: Record<string, Glyph>;
  checks: Record<string, GlyphCheck>;
  breakChecks: Partial<Record<BreakKey, BreakCheck>>;
  /** Output files, relative to the repo root. */
  files: Record<string, string>;
}

const U = UNITS_PER_EM;
const round = (n: number) => Math.round(n) || 0;
const pt = ([x, y]: Point): Point => [round(x), round(y)];
const deg = (n: number) => Math.round(n * 10) / 10 || 0;

function loadFonts(config: GlyphsConfig): Font[] {
  const require = createRequire(import.meta.url);
  return config.fonts.map((spec) => {
    const font = create(readFileSync(require.resolve(spec)));
    if (font.isCollection) throw new Error(`${spec}: font collections are not supported`);
    // Static instances name the weight in the family ("Playfair Display Black").
    const family = font.familyName.startsWith(config.family);
    if (!family || font['OS/2'].usWeightClass !== config.weight) {
      throw new Error(
        `${spec} is ${font.familyName} ${font['OS/2'].usWeightClass}, config says ${config.family} ${config.weight}`,
      );
    }
    return font;
  });
}

/** The glyph's outline in glyph units, y down, rounded to integers. */
function outline(font: Font, cp: number): { commands: Command[]; adv: number } {
  const g = font.glyphForCodePoint(cp);
  const k = U / font.unitsPerEm;
  const x = (v: number) => round(v * k);
  const y = (v: number) => round(-v * k);
  const commands = g.path.commands.map((c): Command => {
    const a = c.args;
    switch (c.command) {
      case 'moveTo':
        return ['M', x(a[0] ?? 0), y(a[1] ?? 0)];
      case 'lineTo':
        return ['L', x(a[0] ?? 0), y(a[1] ?? 0)];
      case 'quadraticCurveTo':
        return ['Q', x(a[0] ?? 0), y(a[1] ?? 0), x(a[2] ?? 0), y(a[3] ?? 0)];
      case 'bezierCurveTo':
        return [
          'C',
          x(a[0] ?? 0),
          y(a[1] ?? 0),
          x(a[2] ?? 0),
          y(a[3] ?? 0),
          x(a[4] ?? 0),
          y(a[5] ?? 0),
        ];
      case 'closePath':
        return ['Z'];
    }
    throw new Error(`unknown path command ${c.command}`);
  });
  return { commands, adv: x(g.advanceWidth) };
}

/** Nails for a glyph that never falls: one, two or four by ink size. */
function fixedTargets(ink: Box, config: GlyphsConfig): Point[] {
  const [x0, y0, x1, y1] = ink;
  const w = x1 - x0;
  const h = y1 - y0;
  const size = Math.max(w, h) / U;
  const cx = (x0 + x1) / 2;
  const cy = (y0 + y1) / 2;
  if (size < config.fixedNails.one) return [[cx, cy]];
  if (size < config.fixedNails.two) {
    return w >= h
      ? [
          [x0 + 0.12 * w, cy],
          [x1 - 0.12 * w, cy],
        ]
      : [
          [cx, y0 + 0.12 * h],
          [cx, y1 - 0.12 * h],
        ];
  }
  return nailTargets(ink, false);
}

/** Every character the fonts can draw on the board, in code point order. */
function boardCharset(fonts: Font[], config: GlyphsConfig): string[] {
  const cps = new Set(fonts.flatMap((f) => f.characterSet));
  return [...cps]
    .sort((a, b) => a - b)
    .map((cp) => String.fromCodePoint(cp))
    .filter((ch) => config.drawable.test(ch) && ch.toUpperCase() === ch && !/^\p{Ll}$/u.test(ch));
}

const HEADER = (what: string) =>
  `// Generated by packages/transom/scripts/gen-glyphs.ts from glyphs.config.ts — do not edit.\n// ${what}\n// Regenerate: task transom:glyphs\n`;

function table(name: string, glyphs: [string, Glyph][], what: string): string {
  const rows = glyphs.map(([ch, g]) => `  ${JSON.stringify(ch)}: ${JSON.stringify(g)},`);
  return `${HEADER(what)}import type { GlyphTable } from './glyphs';\n\nexport const ${name}: GlyphTable = {\n${rows.join('\n')}\n};\n`;
}

export function buildGlyphs(config: GlyphsConfig = GLYPHS_CONFIG): GlyphBuild {
  const fonts = loadFonts(config);
  const charset = boardCharset(fonts, config);
  const scale = config.pxPerEm / U;
  const glyphs: Record<string, Glyph> = {};
  const checks: Record<string, GlyphCheck> = {};
  const breakChecks: Partial<Record<BreakKey, BreakCheck>> = {};

  for (const ch of charset) {
    const cp = ch.codePointAt(0) ?? 0;
    const font = fonts.find((f) => f.glyphForCodePoint(cp).id !== 0);
    if (!font) throw new Error(`no glyph for ${ch}`);
    const { commands, adv } = outline(font, cp);
    const grid = rasterize(commands, scale);
    const inkExact = inkBox(grid, config.inkAlpha);
    const ink = inkExact.map(round) as unknown as Box;
    const falls = config.falling.test(ch);
    const base = { d: pathData(commands), adv, ink, falls };

    if (!falls) {
      const nails = snapNails(grid, fixedTargets(ink, config), undefined, config.nailAlpha, pt);
      glyphs[ch] = { ...base, nails: nails.map(pt) };
      checks[ch] = {};
      continue;
    }

    const rivets = config.rivets.includes(ch);
    const targets = nailTargets(ink, rivets);
    const hinge = config.hinges[ch];
    if (hinge) targets[0] = inkPoint(ink, hinge);
    const nails = snapNails(grid, targets, undefined, config.nailAlpha, pt);
    const exact = outlineCentroid(commands);
    const raster = centroid(grid);
    const cen = pt(exact);
    const glyph: Glyph = {
      ...base,
      nails,
      centroid: cen,
      hang: deg(hangAngle(nails[0] as Point, cen)),
      drop: round(dropFor(ink[3] / U) * U),
    };
    checks[ch] = {
      centroidDelta: Math.hypot(exact[0] - raster[0], exact[1] - raster[1]) / U,
    };

    const keys = breaksFor(ch);
    if (keys.length) {
      const breaks: Partial<Record<BreakKey, GlyphBreak>> = {};
      for (const key of keys) {
        const poly = piecePolygon(PIECES[key], adv, ink).map(pt);
        const bNails = snapNails(grid, targets, poly, config.nailAlpha, pt);
        const rest = pt(centroid(grid, poly));
        const pcen = pt(centroid(grid, poly, true));
        breaks[key] = {
          poly,
          centroid: pcen,
          drop: round(pieceDropFor(ink[3] / U, pcen[1] / U) * U),
          nails: bNails,
          rest,
          hang: deg(hangAngle(bNails[0] as Point, rest)),
        };
        breakChecks[key] = {
          ...splitInk(grid, poly, config.inkAlpha),
          regions: inkRegions(grid, poly, config.inkAlpha),
        };
      }
      glyph.breaks = breaks;
    }
    glyphs[ch] = glyph;
  }

  const falling = charset.filter((ch) => glyphs[ch]?.falls);
  const coreSet = new Set(Array.from(config.core));
  const entries = charset.map((ch): [string, Glyph] => [ch, glyphs[ch] as Glyph]);
  const files = {
    'packages/transom/src/glyphs.core.gen.ts': table(
      'GLYPHS_CORE',
      entries.filter(([ch]) => coreSet.has(ch)),
      'Common characters, shipped with every board.',
    ),
    'packages/transom/src/glyphs.ext.gen.ts': table(
      'GLYPHS_EXT',
      entries.filter(([ch]) => !coreSet.has(ch)),
      'The rest of the charset, loaded on demand (loadExt).',
    ),
    'packages/core/src/charset.gen.ts': `${HEADER(`${config.family} ${config.weight}: ${charset.length} characters.`)}
/** Every character the transom can draw. */
export const BOARD_CHARSET = ${JSON.stringify(charset.join(''))};

/** The characters that can fall off or break (letters and digits); the rest stay nailed on. */
export const FALLING = ${JSON.stringify(falling.join(''))};
`,
  };
  return { charset, falling, glyphs, checks, breakChecks, files };
}
